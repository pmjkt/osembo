-- Osembo database setup. Run this whole file once in Supabase: SQL Editor > New query > Run.
-- Safe to run again.

-- 1. Main data table (one row per school)
create table if not exists app_state (
  id bigint generated by default as identity primary key,
  school_id text not null default 'osembo-main',
  data jsonb not null,
  updated_at timestamptz default now()
);
create unique index if not exists app_state_school_id_uq on app_state (school_id);

-- 2. Subscription table: the school can use the app only while paid_until is in the future
create table if not exists subscriptions (
  school_id text primary key,
  paid_until timestamptz not null
);

-- 3. Turn on security
alter table app_state enable row level security;
alter table subscriptions enable row level security;

-- 4. Remove the old open pilot rules
drop policy if exists "Allow public read/write during pilot" on app_state;
drop policy if exists "staff access" on app_state;
drop policy if exists "paid staff access" on app_state;

-- 5. Only logged-in staff, and only while the subscription is active
create policy "paid staff access" on app_state
  for all to authenticated
  using (exists (select 1 from subscriptions s
                 where s.school_id = app_state.school_id and s.paid_until > now()))
  with check (exists (select 1 from subscriptions s
                 where s.school_id = app_state.school_id and s.paid_until > now()));

-- 6. Logged-in staff can read the subscription date (so the app can show it)
drop policy if exists "staff read subscription" on subscriptions;
create policy "staff read subscription" on subscriptions
  for select to authenticated using (true);

-- 7. Starting subscription for the school: one month from today (change it later)
insert into subscriptions (school_id, paid_until)
values ('osembo-main', now() + interval '1 month')
on conflict (school_id) do nothing;

-- 8. M-Pesa payment records (written only by the server functions)
create table if not exists mpesa_payments (
  id uuid primary key default gen_random_uuid(),
  school_id text not null,
  phone text not null,
  amount int not null,
  months int not null default 1,
  checkout_request_id text unique not null,
  status text not null default 'pending',
  receipt text,
  result text,
  created_at timestamptz default now(),
  paid_at timestamptz
);
alter table mpesa_payments enable row level security;
-- No policies: the app cannot read or change this table. Only the server functions can.
